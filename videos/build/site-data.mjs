#!/usr/bin/env node
/* Emit js/data-videos.js from rendered timelines + YouTube metadata. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const tlDir = path.join(root, "videos/studio/timelines");
const ytDir = path.join(root, "videos/youtube");
const out = path.join(root, "js/data-videos.js");

const files = fs.readdirSync(tlDir).filter((f) => /^bai\d{2}\.json$/.test(f)).sort();

const chapterOrder = [];
const videos = files.map((file) => {
  const t = JSON.parse(fs.readFileSync(path.join(tlDir, file), "utf8"));
  let meta = {};
  const metaFile = path.join(ytDir, t.id, "metadata.json");
  if (fs.existsSync(metaFile)) meta = JSON.parse(fs.readFileSync(metaFile, "utf8"));
  if (!chapterOrder.includes(t.chapterName)) chapterOrder.push(t.chapterName);
  return {
    id: t.id,
    num: t.num,
    title: t.title,
    chapter: t.chapter,
    chapterName: t.chapterName,
    project: t.project,
    submitFile: t.submitFile,
    tech: t.tech || [],
    hasJs: Boolean(t.hasJs),
    duration: Math.round(t.total),
    poster: `videos/youtube/${t.id}/thumbnail.jpg`,
    media: `videos/media/${t.id}.mp4`,
    youtubeId: meta.youtubeId || "",
    scenes: (t.scenes || []).map((s) => ({
      t: Math.round(s.start * 10) / 10,
      label: s.label || s.type,
      type: s.type
    }))
  };
});

const chapters = chapterOrder.map((name) => ({
  name,
  ids: videos.filter((v) => v.chapterName === name).map((v) => v.id)
}));

const body = `/* Generated by videos/build/site-data.mjs — do not edit by hand. */
window.FRONTLAB_VIDEOS = ${JSON.stringify({ chapters, videos }, null, 1)};
`;
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(root, out)} — ${videos.length} videos, ${chapters.length} chapters`);
